-- 1. USUARIOS / PROFISSIONAIS
CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    papel VARCHAR(30) NOT NULL DEFAULT 'profissional'
        CHECK (papel IN ('admin', 'profissional', 'recepcionista')),
    numero_registro VARCHAR(50),
    tipo_registro VARCHAR(50),
    telefone VARCHAR(30),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. PACIENTES
CREATE TABLE IF NOT EXISTS public.pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    nome_social VARCHAR(150),
    cpf VARCHAR(14) UNIQUE,
    rg VARCHAR(30),
    data_nascimento DATE,
    genero VARCHAR(20) DEFAULT 'nao_informado'
        CHECK (genero IN ('masculino', 'feminino', 'outro', 'nao_informado')),
    telefone VARCHAR(30),
    whatsapp VARCHAR(30),
    email VARCHAR(150),
    endereco VARCHAR(255),
    cidade VARCHAR(100),
    estado CHAR(2),
    cep VARCHAR(10),
    contato_emergencia VARCHAR(150),
    telefone_emergencia VARCHAR(30),
    alergias TEXT,
    observacoes TEXT,
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. AGENDA / AGENDAMENTOS / TELECONSULTA
CREATE TABLE IF NOT EXISTS public.agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    profissional_id BIGINT NOT NULL,
    data_agendamento DATE NOT NULL,
    hora_inicio TIME WITHOUT TIME ZONE NOT NULL,
    hora_fim TIME WITHOUT TIME ZONE,
    tipo VARCHAR(20) NOT NULL DEFAULT 'consulta'
        CHECK (tipo IN ('consulta', 'massagem', 'procedimento', 'retorno', 'outro')),
    situacao VARCHAR(20) NOT NULL DEFAULT 'agendado'
        CHECK (situacao IN ('agendado', 'confirmado', 'em_atendimento', 'concluido', 'cancelado', 'faltou')),
    origem_agendamento VARCHAR(20) NOT NULL DEFAULT 'interno'
        CHECK (origem_agendamento IN ('interno', 'online', 'whatsapp')),
    teleconsulta BOOLEAN NOT NULL DEFAULT FALSE,
    url_reuniao VARCHAR(500),
    observacoes TEXT,
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_agendamentos_paciente
        FOREIGN KEY (paciente_id) REFERENCES public.pacientes(id) ON DELETE RESTRICT,
    CONSTRAINT fk_agendamentos_profissional
        FOREIGN KEY (profissional_id) REFERENCES public.usuarios(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_agendamentos_data
    ON public.agendamentos (data_agendamento);
CREATE INDEX IF NOT EXISTS idx_agendamentos_paciente
    ON public.agendamentos (paciente_id);
CREATE INDEX IF NOT EXISTS idx_agendamentos_profissional
    ON public.agendamentos (profissional_id);

-- 4. PRONTUARIO ELETRONICO
CREATE TABLE IF NOT EXISTS public.prontuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    profissional_id BIGINT NOT NULL,
    agendamento_id BIGINT,
    data_registro TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    queixa TEXT,
    historico_clinico TEXT,
    diagnostico TEXT,
    tratamento TEXT,
    observacoes TEXT,
    peso DECIMAL(6,2),
    altura DECIMAL(5,2),
    pressao_arterial VARCHAR(20),
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prontuarios_paciente
        FOREIGN KEY (paciente_id) REFERENCES public.pacientes(id) ON DELETE RESTRICT,
    CONSTRAINT fk_prontuarios_profissional
        FOREIGN KEY (profissional_id) REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    CONSTRAINT fk_prontuarios_agendamento
        FOREIGN KEY (agendamento_id) REFERENCES public.agendamentos(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_prontuarios_paciente
    ON public.prontuarios (paciente_id);
CREATE INDEX IF NOT EXISTS idx_prontuarios_data
    ON public.prontuarios (data_registro);

-- 5. PRESCRICOES
CREATE TABLE IF NOT EXISTS public.prescricoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    profissional_id BIGINT NOT NULL,
    prontuario_id BIGINT,
    data_prescricao TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    situacao VARCHAR(20) NOT NULL DEFAULT 'rascunho'
        CHECK (situacao IN ('rascunho', 'emitida', 'cancelada')),
    assinatura_digital TEXT,
    assinado_em TIMESTAMP WITHOUT TIME ZONE,
    observacoes TEXT,
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prescricoes_paciente
        FOREIGN KEY (paciente_id) REFERENCES public.pacientes(id) ON DELETE RESTRICT,
    CONSTRAINT fk_prescricoes_profissional
        FOREIGN KEY (profissional_id) REFERENCES public.usuarios(id) ON DELETE RESTRICT,
    CONSTRAINT fk_prescricoes_prontuario
        FOREIGN KEY (prontuario_id) REFERENCES public.prontuarios(id) ON DELETE SET NULL
);

-- 6. ITENS DA PRESCRICAO
CREATE TABLE IF NOT EXISTS public.itens_prescricao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescricao_id BIGINT NOT NULL,
    nome_medicamento VARCHAR(200) NOT NULL,
    principio_ativo VARCHAR(200),
    apresentacao VARCHAR(150),
    concentracao VARCHAR(100),
    dosagem VARCHAR(100),
    via_administracao VARCHAR(100),
    frequencia VARCHAR(100),
    duracao VARCHAR(100),
    quantidade VARCHAR(100),
    instrucoes TEXT,
    -- PostgreSQL usa JSONB para armazenamento e consulta eficiente de JSON.
    dados_dosagem JSONB,
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_itens_prescricao_prescricao
        FOREIGN KEY (prescricao_id) REFERENCES public.prescricoes(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_itens_prescricao_medicamento
    ON public.itens_prescricao (nome_medicamento);

-- 7. DOCUMENTOS
CREATE TABLE IF NOT EXISTS public.documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT,
    profissional_id BIGINT,
    tipo VARCHAR(30) NOT NULL
        CHECK (tipo IN ('receita', 'encaminhamento', 'atestado', 'documento', 'outro')),
    titulo VARCHAR(200) NOT NULL,
    caminho_arquivo VARCHAR(500),
    hash_documento VARCHAR(255),
    assinado_digitalmente BOOLEAN NOT NULL DEFAULT FALSE,
    assinado_em TIMESTAMP WITHOUT TIME ZONE,
    emitido_em TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_documentos_paciente
        FOREIGN KEY (paciente_id) REFERENCES public.pacientes(id) ON DELETE SET NULL,
    CONSTRAINT fk_documentos_profissional
        FOREIGN KEY (profissional_id) REFERENCES public.usuarios(id) ON DELETE SET NULL
);

-- 8. FINANCEIRO
CREATE TABLE IF NOT EXISTS public.transacoes_financeiras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT,
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('receita', 'despesa')),
    descricao VARCHAR(255) NOT NULL,
    valor DECIMAL(12,2) NOT NULL,
    data_vencimento DATE,
    pago_em TIMESTAMP WITHOUT TIME ZONE,
    situacao VARCHAR(20) NOT NULL DEFAULT 'pendente'
        CHECK (situacao IN ('pendente', 'pago', 'cancelado')),
    forma_pagamento VARCHAR(30)
        CHECK (forma_pagamento IN ('dinheiro', 'pix', 'cartao_credito', 'cartao_debito', 'transferencia', 'convenio', 'outro')),
    -- Dados basicos para futura integracao TISS.
    tiss_habilitado BOOLEAN NOT NULL DEFAULT FALSE,
    codigo_tiss VARCHAR(50),
    nome_convenio VARCHAR(150),
    numero_carteirinha VARCHAR(100),
    observacoes TEXT,
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_transacoes_financeiras_paciente
        FOREIGN KEY (paciente_id) REFERENCES public.pacientes(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_transacoes_financeiras_situacao
    ON public.transacoes_financeiras (situacao);
CREATE INDEX IF NOT EXISTS idx_transacoes_financeiras_vencimento
    ON public.transacoes_financeiras (data_vencimento);

-- 9. ESTOQUE
CREATE TABLE IF NOT EXISTS public.itens_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    categoria VARCHAR(30) NOT NULL DEFAULT 'insumo'
        CHECK (categoria IN ('medicamento', 'vitamina', 'insumo', 'cosmetico', 'outro')),
    descricao TEXT,
    unidade VARCHAR(30) NOT NULL DEFAULT 'unidade',
    quantidade_atual DECIMAL(10,2) NOT NULL DEFAULT 0,
    quantidade_minima DECIMAL(10,2) NOT NULL DEFAULT 0,
    numero_lote VARCHAR(100),
    data_validade DATE,
    preco_compra DECIMAL(12,2),
    preco_venda DECIMAL(12,2),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_itens_estoque_nome
    ON public.itens_estoque (nome);
CREATE INDEX IF NOT EXISTS idx_itens_estoque_validade
    ON public.itens_estoque (data_validade);

-- 10. WHATSAPP / E-MAIL / LEMBRETES
CREATE TABLE IF NOT EXISTS public.comunicacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    agendamento_id BIGINT,
    canal VARCHAR(20) NOT NULL
        CHECK (canal IN ('whatsapp', 'email')),
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('lembrete', 'confirmacao', 'retorno', 'outro')),
    destinatario VARCHAR(200) NOT NULL,
    assunto VARCHAR(255),
    mensagem TEXT NOT NULL,
    situacao VARCHAR(20) NOT NULL DEFAULT 'pendente'
        CHECK (situacao IN ('pendente', 'enviado', 'entregue', 'lido', 'erro')),
    agendado_para TIMESTAMP WITHOUT TIME ZONE,
    enviado_em TIMESTAMP WITHOUT TIME ZONE,
    id_externo VARCHAR(255),
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_comunicacoes_paciente
        FOREIGN KEY (paciente_id) REFERENCES public.pacientes(id) ON DELETE CASCADE,
    CONSTRAINT fk_comunicacoes_agendamento
        FOREIGN KEY (agendamento_id) REFERENCES public.agendamentos(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_comunicacoes_situacao
    ON public.comunicacoes (situacao);
CREATE INDEX IF NOT EXISTS idx_comunicacoes_agendado
    ON public.comunicacoes (agendado_para);

-- ============================================================
-- ATUALIZACAO AUTOMATICA DE atualizado_em
-- MySQL fazia isso com ON UPDATE CURRENT_TIMESTAMP.
-- No PostgreSQL, um trigger reproduz esse comportamento.
-- ============================================================
CREATE OR REPLACE FUNCTION public.atualizar_coluna_atualizado_em()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.atualizado_em := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_usuarios_atualizado_em ON public.usuarios;
CREATE TRIGGER trg_usuarios_atualizado_em
    BEFORE UPDATE ON public.usuarios
    FOR EACH ROW EXECUTE FUNCTION public.atualizar_coluna_atualizado_em();

DROP TRIGGER IF EXISTS trg_pacientes_atualizado_em ON public.pacientes;
CREATE TRIGGER trg_pacientes_atualizado_em
